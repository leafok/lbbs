// A filtered menu narrows its list down by asking the item itself, which is what
// use_filter hands to the handler
static int test_filter_handler(void *p_param)
{
	const MENU_ITEM *p_item = (const MENU_ITEM *)p_param;

	filter_calls++;

	return (p_item->level >= 1 ? 1 : 0);
}

bbs_cmd_handler get_cmd_handler(const char *cmd)
{
	if (cmd == NULL)
	{
		return NULL;
	}

	if (strcmp(cmd, "TOPACT") == 0 || strcmp(cmd, "SUBACT") == 0)
	{
		return test_action_handler;
	}

	if (strcmp(cmd, "FILTERMENU") == 0)
	{
		return test_filter_handler;
	}

	return NULL;
}

