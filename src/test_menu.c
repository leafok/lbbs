	check_int(menu_control(&ms_main, CR), REDRAW, "CR on the !.. item");
	check_int(ms_main.choose_step, 0, "!.. pops the path");

	set_cursor(&ms_main, 0);
	check_int(menu_control(&ms_main, CR), NOREDRAW, "CR into SUB1 again");
	check_int(menu_control(&ms_main, KEY_DOWN), NOREDRAW, "KEY_DOWN inside SUB1");
	check_int(ms_main.menu_item_pos[1], 1, "SUB1 cursor on its command item");

	reset_screen_log();
	check_int(menu_control(&ms_main, CR), 0, "CR on a command item returns what the handler did");
	check_int(action_calls, 1, "the command handler ran once");
	check_str(action_name, "Go", "the handler was given the item name");
	check_int(ms_main.choose_step, 1, "a command does not touch the path");

	check_int(menu_control(&ms_main, KEY_ESC), REDRAW, "KEY_ESC inside a submenu");
	check_int(ms_main.choose_step, 0, "KEY_ESC pops the path");

	// At the top level ESC either leaves the menu or looks for the way out
	ms_main.allow_exit = 1;
	check_int(menu_control(&ms_main, KEY_ESC), EXITMENU, "KEY_ESC with allow_exit");

	ms_main.allow_exit = 0;
	set_cursor(&ms_main, 2);
	check_int(menu_control(&ms_main, KEY_LEFT), NOREDRAW, "KEY_LEFT at the top level");
	check_int(get_cursor(&ms_main), 0, "KEY_LEFT falls back on the item that asks for nothing");

