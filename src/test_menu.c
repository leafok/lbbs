static void test_limits(void)
{
	MENU_SET ms;
	MENU *p_menu;
	MENU_SCREEN *p_screen;
	char path[64];
	char line[MAX_MENU_SCR_BUF_LENGTH / 2 + 1];
	FILE *f;
	int i;
	int lines;
	int line_len;
	int line_cost;
	int last_byte;
	int shape;

	snprintf(path, sizeof(path), "~test_menu_items.conf");

	check_int(write_grid_conf(path, 1, MAX_ITEMS_PER_MENU), 0, "write a menu at the item limit");
	memset(&ms, 0, sizeof(ms));
	check_int(load_menu(&ms, path), 0, "load_menu() of a menu with MAX_ITEMS_PER_MENU items");
	check_int(ms.menu_count, 1, "menu_count of the full menu");
	check_int(ms.menu_item_count, MAX_ITEMS_PER_MENU, "menu_item_count of the full menu");
	p_menu = get_menu_by_id(&ms, 0);
	check_record(p_menu, "the full menu record");
	check_int(rec_int(p_menu, item_count), MAX_ITEMS_PER_MENU, "item_count of the full menu");
	unload_menu(&ms);

	check_int(write_grid_conf(path, 1, MAX_ITEMS_PER_MENU + 1), 0, "write a menu past the item limit");
	memset(&ms, 0, sizeof(ms));
	check_int(load_menu(&ms, path), -1, "load_menu() past MAX_ITEMS_PER_MENU");
	unload_menu(&ms);

	// The item pool of all menus together holds MAX_MENUITEMS records
	check_int(write_grid_conf(path, MAX_MENUITEMS / MAX_ITEMS_PER_MENU, MAX_ITEMS_PER_MENU), 0,
			  "write the config at the global item limit");
	memset(&ms, 0, sizeof(ms));
	check_int(load_menu(&ms, path), 0, "load_menu() with MAX_MENUITEMS items");
	check_int(ms.menu_item_count, MAX_MENUITEMS, "menu_item_count at the global item limit");
	unload_menu(&ms);

	check_int(write_grid_conf(path, MAX_MENUITEMS / MAX_ITEMS_PER_MENU + 1, MAX_ITEMS_PER_MENU), 0,
			  "write the config past the global item limit");
	memset(&ms, 0, sizeof(ms));
	check_int(load_menu(&ms, path), -3, "load_menu() past MAX_MENUITEMS");
	unload_menu(&ms);
	unlink(path);

	snprintf(path, sizeof(path), "~test_menu_menus.conf");

	check_int(write_grid_conf(path, MAX_MENUS, 0), 0, "write the config at the menu limit");
	memset(&ms, 0, sizeof(ms));
	check_int(load_menu(&ms, path), 0, "load_menu() with MAX_MENUS menus");
	check_int(ms.menu_count, MAX_MENUS, "menu_count at the limit");
	unload_menu(&ms);

	check_int(write_grid_conf(path, MAX_MENUS + 1, 0), 0, "write the config past the menu limit");
	memset(&ms, 0, sizeof(ms));
	check_int(load_menu(&ms, path), -3, "load_menu() past MAX_MENUS");
	unload_menu(&ms);
	unlink(path);

	snprintf(path, sizeof(path), "~test_menu_screens.conf");

	// Screen records share the MAX_MENUS limit of the menus
	f = fopen(path, "w");
	if (f != NULL)
	{
		for (i = 0; i < MAX_MENUS + 1; i++)
		{
			fprintf(f, "%%S%03d\nscreen text\n%%\n", i);
		}

		fclose(f);

		memset(&ms, 0, sizeof(ms));
		check_int(load_menu(&ms, path), -3, "load_menu() past MAX_MENUS screens");
		unload_menu(&ms);
		unlink(path);
	}

	// The screen text of all screens together lives in one buffer of MAX_MENU_SCR_BUF_LENGTH
	// bytes per screen. A config line costs the clear-line sequence in front of it, its own
	// bytes, the carriage return inserted before its newline and the newline it pays for. Short
	// lines leave little room in the last reservation, which is where the clear-line check is
	// the only thing keeping the buffer from being written past its last byte.
	snprintf(path, sizeof(path), "~test_menu_bufsize.conf");
	last_byte = MAX_MENU_SCR_BUF_LENGTH * MAX_MENUS - 1;

	for (shape = 0; shape < 2; shape++)
	{
		line_len = (shape == 0) ? 1 : MAX_MENU_SCR_BUF_LENGTH / 2;
		line_cost = line_len + (int)strlen(CTRL_SEQ_CLR_LINE) + 2;
		lines = (MAX_MENU_SCR_BUF_LENGTH * MAX_MENUS - 2) / line_cost;

		fill_chars(line, line_len, 'x');

		check_int(load_screen_of_lines(&ms, path, line, lines), 0,
				  "load_menu() with a screen at the buffer limit");
		p_screen = get_menu_screen_by_id(&ms, 0);
		check_record(p_screen, "the screen record at the buffer limit");
		check_int(rec_int(p_screen, buf_length), lines * line_cost + 1,
				  "the screen at the buffer limit uses every byte it reserved");
		check_true(ms.p_menu_screen_buf != NULL && ms.p_menu_screen_buf[last_byte] == '\0',
				   "the last byte of the screen buffer stays free");
		unload_menu(&ms);

		check_int(load_screen_of_lines(&ms, path, line, lines + 1), -3,
				  "load_menu() past the screen buffer");
		check_true(ms.p_menu_screen_buf != NULL && ms.p_menu_screen_buf[last_byte] == '\0',
				   "the rejected screen stops short of the last byte");
		unload_menu(&ms);

		unlink(path);
	}
}

static sigjmp_buf paging_env;
static volatile sig_atomic_t paging_timeout;

static void paging_alarm(int signum)
{
	(void)signum;

	paging_timeout = 1;
	siglongjmp(paging_env, 1);
}

// A scan that keeps wrapping around would hang the run instead of answering, so the calls over
// a menu with nothing to show are guarded by an alarm and report a failed check
static int menu_control_paged(MENU_SET *p_menu_set, int key)
{
	int ret;

	paging_timeout = 0;

	if (sigsetjmp(paging_env, 1) != 0)
	{
		return -1;
	}

	signal(SIGALRM, paging_alarm);
	alarm(5);
	ret = menu_control(p_menu_set, key);
	alarm(0);
	signal(SIGALRM, SIG_DFL);

	return ret;
}

static void test_hardening(void)
{
	MENU_SET ms;
	MENU *p_menu;
	char conf[LINE_BUFFER_LEN];
	char path[64];
	int i;
	int ret;

	// Reloading a set has to hand back the mapping it already holds, or the reset at the top of
	// load_menu() orphans it along with the shared memory object it names
	snprintf(path, sizeof(path), "~test_menu_reload.conf");
	build_conf(conf, sizeof(conf), "screen 0, 0, S\n!.. 0, 0, 0, 0, \"N\", \"t\"\n");

	if (write_text_file(path, conf) == 0)
	{
		memset(&ms, 0, sizeof(ms));
		check_int(load_menu(&ms, path), 0, "load_menu() of the config to reload");
		check_int(count_mappings(ms.shm_name), 1, "the loaded config is mapped once");
		check_int(load_menu(&ms, path), 0, "load_menu() of the same set a second time");
		check_int(count_mappings(ms.shm_name), 1, "the reload replaced the mapping of the first load");
		p_menu = get_menu_by_id(&ms, 0);
		check_record(p_menu, "the menu of the reloaded set");
		check_str(rec_str(p_menu, name), "MENU1", "the reloaded set has the same menus");
		check_int(unload_menu(&ms), 0, "unload_menu() of the reloaded set");
		check_int(count_mappings(ms.shm_name), 0, "the reloaded set leaves no mapping behind");
		unlink(path);
	}

	// The path arrays hold one entry per level, so a ring of menus has to stop at the last one
	snprintf(path, sizeof(path), "~test_menu_chain.conf");
	check_int(write_chain_conf(path, MAX_MENU_DEPTH + 5), 0, "write the config of nested menus");
	memset(&ms, 0, sizeof(ms));
	check_int(load_menu(&ms, path), 0, "load_menu() of the nested config");
	check_int(ms.menu_count, MAX_MENU_DEPTH + 5, "menu_count of the nested config");

	for (i = 0; i < MAX_MENU_DEPTH + 5; i++)
	{
		ret = menu_control(&ms, KEY_RIGHT);
	}

	check_int(ret, NOREDRAW, "KEY_RIGHT past the last level redraws nothing");
	check_int(ms.choose_step, MAX_MENU_DEPTH - 1, "choose_step stops at the last level");

	for (i = 0; i < ms.choose_step; i++)
	{
		p_menu = get_menu_by_id(&ms, ms.menu_id_path[i]);
		check_record(p_menu, "a level of the menu path");
	}

	p_menu = get_menu_by_id(&ms, ms.menu_id_path[ms.choose_step]);
	check_record(p_menu, "the deepest menu");
	check_str(rec_str(p_menu, name), "M49", "the deepest menu is the last level");
	check_int(unload_menu(&ms), 0, "unload_menu() of the nested config");
	unlink(path);

	// A menu whose items are all hidden leaves the cursor nowhere to go, which the paging and the
	// way out both have to survive
	snprintf(path, sizeof(path), "~test_menu_hidden.conf");

	if (write_text_file(path,
						"%S\nscreen text\n%\n"
						"%menu HIDDEN\nscreen 0, 0, S\n"
						"!.. 0, 0, 0, 40, \"N1\", \"t1\"\n"
						"!.. 1, 0, 0, 40, \"N2\", \"t2\"\n"
						"%\n") == 0)
	{
		memset(&ms, 0, sizeof(ms));
		check_int(load_menu(&ms, path), 0, "load_menu() of the config with nothing to show");
		set_priv(P_USER, S_LIST);
		reset_screen_log();
		check_int(display_menu(&ms), -1, "display_menu() with nothing to show");
		check_int(press_any_key_count, 1, "the menu with nothing to show asked for a key");
		check_int(ms.menu_item_display[0], 0, "the first item is hidden");
		check_int(ms.menu_item_display[1], 0, "the second item is hidden");
		check_int(get_cursor(&ms), 0, "the cursor of a menu with nothing to show");

		ms.allow_exit = 0;
		check_int(menu_control(&ms, KEY_LEFT), NOREDRAW, "KEY_LEFT with no exit allowed");
		check_int(get_cursor(&ms), 0, "KEY_LEFT keeps the cursor on a real item");
		check_int(menu_control_paged(&ms, KEY_DOWN), NOREDRAW, "KEY_DOWN turns once around the hidden items");
		check_int(paging_timeout, 0, "KEY_DOWN came back instead of turning for ever");
		check_int(menu_control_paged(&ms, KEY_UP), NOREDRAW, "KEY_UP turns once around the hidden items");
		check_int(paging_timeout, 0, "KEY_UP came back instead of turning for ever");
		check_int(menu_control_paged(&ms, KEY_PGDN), NOREDRAW, "KEY_PGDN around the hidden items");
		check_int(menu_control_paged(&ms, KEY_PGUP), NOREDRAW, "KEY_PGUP around the hidden items");
		check_int(paging_timeout, 0, "the page keys came back instead of turning for ever");
		check_int(get_cursor(&ms), 0, "the cursor is still on a real item");
		unload_menu(&ms);
		unlink(path);
	}

	// The extended key codes are far past the range of the ctype tables, and only a printable
	// character can name a hot key
	check_int(load_menu(&ms_main, MAIN_CONF_FILE), 0, "load_menu() for the hot key tests");
	ms_main.allow_exit = 1;
	set_priv(P_USER, S_LIST);
	check_int(display_menu(&ms_main), 0, "display_menu() for the hot key tests");
	set_cursor(&ms_main, 1);

	check_int(menu_control(&ms_main, KEY_F1), NOREDRAW, "KEY_F1 is not a hot key");
	check_int(get_cursor(&ms_main), 1, "KEY_F1 leaves the cursor where it was");
	check_int(menu_control(&ms_main, KEY_INS), NOREDRAW, "KEY_INS is not a hot key");
	check_int(menu_control(&ms_main, KEY_NULL), NOREDRAW, "KEY_NULL is not a hot key");
	check_int(get_cursor(&ms_main), 1, "the extended codes leave the cursor where it was");
	check_int(menu_control(&ms_main, 'a'), NOREDRAW, "the hot key of item 0");
	check_int(get_cursor(&ms_main), 0, "the hot key selects its item");
	check_int(menu_control(&ms_main, 'z'), NOREDRAW, "a hot key no item offers");
	check_int(get_cursor(&ms_main), 0, "an unused hot key leaves the cursor alone");
}

