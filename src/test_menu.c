static void test_shm_readonly(void)
{
	MENU_SET ms_ro;
	MENU *p_menu;
	MENU_ITEM *p_item;
	MENU_SCREEN *p_screen;
	MENU_SCREEN *p_screen_rw;

	check_true(shm_object_exists(ms_main.shm_name), "menu shm object exists while loaded");

	check_int(get_menu_shm_readonly(NULL), -1, "get_menu_shm_readonly(NULL)");
	check_int(set_menu_shm_readonly(NULL), -1, "set_menu_shm_readonly(NULL)");
	check_int(detach_menu_shm(NULL), -1, "detach_menu_shm(NULL)");
	check_int(unload_menu(NULL), -1, "unload_menu(NULL)");

	memset(&ms_ro, 0, sizeof(ms_ro));
	snprintf(ms_ro.shm_name, sizeof(ms_ro.shm_name), "%s", ms_main.shm_name);
	check_int(get_menu_shm_readonly(&ms_ro), 0, "get_menu_shm_readonly()");
	check_int((long)ms_ro.shm_size, (long)ms_main.shm_size, "read only shm_size");
	check_true(ms_ro.p_reserved != ms_main.p_reserved, "read only mapping is a second mapping");
	check_true(ms_ro.p_menu_screen_buf ==
				   (char *)ms_ro.p_reserved + sizeof(int16_t) * 4 + sizeof(MENU) * MAX_MENUS +
					   sizeof(MENU_ITEM) * MAX_MENUITEMS + sizeof(MENU_SCREEN) * MAX_MENUS,
			   "read only pools use the same layout");
	check_int(ms_ro.menu_count, 0, "get_menu_shm_readonly() leaves the counts alone");

	// The counts live in the process struct, so a reader restores all three of them from the
	// mapping the way get_section_ex_menu_set() copies them out of the section record
	if (ms_ro.p_reserved != NULL)
	{
		ms_ro.menu_count = *(int16_t *)ms_ro.p_reserved;
		ms_ro.menu_item_count = *((int16_t *)ms_ro.p_reserved + 1);
		ms_ro.menu_screen_count = *((int16_t *)ms_ro.p_reserved + 2);
	}
	check_int(ms_ro.menu_count, 3, "the read only mapping carries menu_count");
	check_int(ms_ro.menu_item_count, 6, "the read only mapping carries menu_item_count");
	check_int(ms_ro.menu_screen_count, 2, "the read only mapping carries menu_screen_count");
	p_menu = get_menu_by_id(&ms_ro, 0);
	p_item = get_menu_item_by_id(&ms_ro, 2);
	p_screen = get_menu_screen_by_id(&ms_ro, 0);
	p_screen_rw = get_menu_screen_by_id(&ms_main, 0);
	check_record(p_menu, "read only menu 0 record");
	check_record(p_item, "read only item 2 record");
	check_record(p_screen, "read only screen 0 record");
	check_record(p_screen_rw, "screen 0 record");
	check_str(rec_str(p_menu, name), "TOPMENU", "read only TOPMENU name");
	check_str(rec_str(p_menu, screen_name), "S_MAIN", "read only screen name");
	check_str(rec_str(p_item, name), "C\"D", "read only item name");
	check_str(rec_buf(ms_ro.p_menu_screen_buf, p_screen, buf_offset),
			  rec_buf(ms_main.p_menu_screen_buf, p_screen_rw, buf_offset), "read only screen text");

	check_int(set_menu_shm_readonly(&ms_ro), 0, "set_menu_shm_readonly()");
	check_str(rec_str(p_menu, title.text), "Top Menu", "read only data survives mprotect");

	check_int(detach_menu_shm(&ms_ro), 0, "detach_menu_shm()");
	check_true(ms_ro.p_reserved == NULL, "detach_menu_shm() clears p_reserved");
	check_true(ms_ro.p_menu_pool == NULL, "detach_menu_shm() clears the pools");
	check_int(ms_ro.menu_count, 0, "detach_menu_shm() clears the counts");
	check_int(detach_menu_shm(&ms_ro), 0, "detach_menu_shm() of an already detached set");

	// The other end of the cycle: the name is released, so the same config loads again
	check_int(unload_menu(&ms_main), 0, "unload_menu()");
	check_true(!shm_object_exists(ms_main.shm_name), "menu shm object gone after unload");
	check_int(unload_menu(&ms_main), 0, "unload_menu() twice in a row");
	check_int(load_menu(&ms_main, MAIN_CONF_FILE), 0, "load_menu() after unload_menu()");

	// load_menu() releases the name before it creates the object, so a second set over an
	// already loaded config is not refused: it takes the name over and both mappings read the
	// same menus until the set that no longer owns the name is unloaded
	{
		MENU_SET ms_again;
		MENU *p_menu_again;

		memset(&ms_again, 0, sizeof(ms_again));
		check_int(load_menu(&ms_again, MAIN_CONF_FILE), 0, "load_menu() of a config loaded twice");
		p_menu_again = get_menu_by_id(&ms_again, 0);
		check_record(p_menu_again, "the second mapping of the config");
		check_str(rec_str(p_menu_again, name), "TOPMENU", "the second mapping has the same menus");
		check_true(shm_object_exists(ms_main.shm_name), "the second set owns the name");
		check_int(unload_menu(&ms_again), 0, "unload_menu() of the second mapping");
		check_true(!shm_object_exists(ms_main.shm_name), "the name goes with the set that owns it");

		// Nothing unmapped the first set, so its mapping still holds what it was loaded with
		p_menu_again = get_menu_by_id(&ms_main, 0);
		check_record(p_menu_again, "the first mapping after the second set was unloaded");
		check_str(rec_str(p_menu_again, name), "TOPMENU", "the first mapping kept its contents");
		check_int(unload_menu(&ms_main), 0, "unload_menu() of the first mapping");
	}
}

